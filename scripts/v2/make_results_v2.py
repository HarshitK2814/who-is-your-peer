"""Generate research/results_v2.md FROM the files in results/v2 (no hand-typed numbers).
Run after every other v2 script: python scripts/v2/make_results_v2.py"""

import json

import numpy as np
import pandas as pd
from common import CHOICE, ROOT, RUNS, SEEN, TAB, hash12, sharpe_ci, slice_period, v1_returns

from peerrel.v2.stylemodel import STYLES

DES = "design 2012-2019 (choice period)"
SEENP = f"2020-2026 {SEEN}"


def J(n):
    return json.load(open(TAB / n))


def md(df: pd.DataFrame, fmt: dict | None = None) -> str:
    fmt = fmt or {}
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float) and pd.isna(v):
                cells.append("")
            elif isinstance(v, (float, np.floating)):
                cells.append(fmt.get(c, "{:.3f}").format(v))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def verdict(b: bool) -> str:
    return "SUPPORTED" if b else "NOT SUPPORTED"


def ci(s, lo, hi) -> str:
    return f"{s:.2f} [{lo:.2f}, {hi:.2f}]"


def main():
    h1, h2, h3, h4 = J("h1_neutral.json"), J("h2_riskmodel.json"), J("h3_turnover.json"), J("overfit_audit.json")
    bc, sk, shp = J("borrow_capacity.json"), J("skfolio_check.json"), J("shap_signal.json")
    bs = pd.read_csv(TAB / "book_stats.csv")
    bsw = pd.read_csv(TAB / "borrow_sweep.csv")
    nav = pd.read_csv(TAB / "capacity_nav_sweep.csv")
    part = pd.read_csv(TAB / "adv_participation.csv")
    shc = pd.read_csv(TAB / "shap_by_characteristic.csv", index_col=0)
    h2c = pd.read_csv(TAB / "h2_by_characteristic.csv", index_col=0)
    run = pd.read_parquet(RUNS / "v2_main" / "returns.parquet")
    pre = pd.read_parquet(RUNS / "v2_prefix_solverfail" / "returns.parquet")
    v1 = pd.read_parquet(ROOT / "results" / "runs" / "20260926-1702_full_main" / "returns.parquet")
    v1c = v1[v1.book == "C_FF49"].set_index("date")
    p = run[run.book == "P_FF49"].set_index("date")
    parity = float((p["excess_ret"] - v1c["excess_ret"]).abs().max())
    n_months = int(p.shape[0])

    o = []
    A = o.append
    A("# P1 v2 results: Who Is Your Peer?, buy-side upgrade")
    A("")
    A(f"Generated by `scripts/v2/make_results_v2.py` from `results/v2/tables/*` and `results/v2/runs/v2_main`. "
      f"Pre-registration v2 hash `{hash12()}` (frozen in commit `prereg-v2: freeze` before any v2 hypothesis statistic). "
      "v1 results are unchanged.")
    A("")
    A("**Timing.** Composite computed at month-end signal bar t (prices <= t, filings filed before t); filled at the t+1 close; "
      "held to the next month's t+1 close. Style-model factor returns use days <= t with exposures lagged one month-end.")
    A("**Costs and capacity (apply to every return below).** $100M NAV, beta-neutral, gross cap 200%, half-spread from the "
      "Abdi-Ranaldo estimate plus square-root impact (Y = 0.5), 20 bp on forced exits, borrow 25/50/150 bp/yr by market-cap rank "
      "(an assumption; no free stock-loan data), excess over the 1-month T-bill. Capacity: see section D2.")
    A(f"**Evidence labels.** `{DES}` is where v2 choices were allowed (values were fixed in the pre-registration, not tuned); it is "
      f"not out-of-sample for the v1 signal and has only 96 monthly signals. `{SEENP}` was reported by v1. "
      "The only unseen data is the forward test (section F).")
    A("")
    A("## Verdicts")
    d2 = h2["periods"]["design 2013-01..2019-12 (choice period)"]
    d3 = h3["periods"][DES]
    A("| Hypothesis | Result (design period) | Verdict |")
    A("|---|---|---|")
    r_sin = h1["rw"]["SIN_FF49"]
    A(f"| H1 industry+style-neutral composite earns a positive net return | SIN_FF49 Sharpe {ci(r_sin['sharpe'], *r_sin['ci95'])}, "
      f"Romano-Wolf p {r_sin['p_rw']:.3f} ({h1['n_months']} months) | {verdict(h1['H1_supported'])} |")
    A(f"| H2 style model forecasts risk better than the PCA-10 model | mean QLIKE gap (PCA minus style) {d2['mean_qlike_diff_pca_minus_style']:.3f}, "
      f"95% CI [{d2['ci95'][0]:.3f}, {d2['ci95'][1]:.3f}], style better in {100 * d2['share_months_style_better']:.0f}% of {d2['n_months']} months | {verdict(h2['H2_supported'])} |")
    A(f"| H3 a 10% turnover cap raises the net Sharpe | T minus V0 Sharpe {d3['diff_ann']:.2f} (HAC p {d3['p_two_sided']:.2f}); "
      f"turnover {d3['T_FF49_turnover']:.3f} vs {d3['V0_FF49_turnover']:.3f}, cost {d3['T_FF49_cost_bps_yr']:.0f} vs {d3['V0_FF49_cost_bps_yr']:.0f} bp/yr | {verdict(h3['H3_supported'])} |")
    A(f"| H4 v1 books are not overfit: PBO < 0.5 and DSR > 0.90 | PBO {h4['pbo']:.2f} ({h4['H4']['pbo_lt_0.5']}), v1 C_FF49 DSR {h4['v1_C_FF49_dsr']:.3f} (n_trials 17) | {verdict(h4['H4']['supported'])} |")
    A("")
    best_ins = h4["best_book_ann_sharpe"]
    A("Reading (generated from the verdict flags): "
      f"v1 C_FF49 design-period Sharpe {ci(h4['v1_C_FF49_sharpe'], *h4['v1_C_FF49_ci95'])}. "
      f"Industry+style neutralisation {'earns' if h1['H1_supported'] else 'does not earn'} a significant positive net return; "
      f"the style model is {'' if h2['H2_supported'] else 'not '}detectably better than the PCA model; "
      f"the turnover cap {'raises' if h3['H3_supported'] else 'does not detectably raise'} the Sharpe. "
      f"PBO {h4['pbo']:.2f} must be read with the best in-sample book Sharpe ({best_ins:.2f}) and the deflated Sharpe "
      f"of C_FF49 ({h4['v1_C_FF49_dsr']:.3f}): a low PBO among books that are all weak is not evidence of a robust book.")
    A("")
    A("## Book table (net of costs and borrow; Sharpe annualised, 95% stationary-bootstrap CI, months = monthly signals)")
    A("")
    t = bs.copy()
    t["Sharpe [95% CI]"] = [ci(a, b, c) for a, b, c in zip(t.sharpe, t.ci_lo, t.ci_hi)]
    t = t[["book", "period", "months", "mean_excess_ann_pct", "Sharpe [95% CI]", "turnover_oneway_per_month", "cost_bps_yr",
           "borrow_bps_yr", "max_abs_style_expo", "turnover_fallback_months"]]
    A(md(t, {"mean_excess_ann_pct": "{:.2f}", "turnover_oneway_per_month": "{:.3f}", "cost_bps_yr": "{:.0f}",
             "borrow_bps_yr": "{:.0f}", "max_abs_style_expo": "{:.2f}"}))
    A("")
    A(f"`v1_C_FF49` is the sealed v1 run; `P_FF49` is the v2 runner with every v2 option off (parity check: max absolute "
      f"monthly difference to v1 over {n_months} months = {parity:.2e}). `turnover_fallback_months` counts months where the 10% "
      "cap was infeasible and the book traded uncapped (flagged, not hidden). `max_abs_style_expo` is the largest absolute "
      "book exposure to any of the 8 styles in any month, in standard-deviation units per unit NAV.")
    A("")
    A("## H1 detail: neutralisation")
    A("")
    rows = [{"book": b, "t": v["t"], "p_RW": v["p_rw"], "Sharpe [95% CI]": ci(v["sharpe"], *v["ci95"])} for b, v in h1["rw"].items()]
    A(md(pd.DataFrame(rows)))
    A("")
    ext = pd.DataFrame([{"hypothesis": k, "t": v["t"], "p_RW": v["p_rw"]} for k, v in h1["rw_extended_v1_B_plus_new"].items()])
    A("Romano-Wolf extended to the v1 industry-bet books plus the new books (7 one-sided tests, 5,000 stationary-bootstrap draws):")
    A("")
    A(md(ext))
    A("")
    sp = pd.DataFrame([{"book": b, "alpha_ann %": 100 * v["alpha_ann"], "alpha t (NW6)": v["alpha_t"], "R2": v["r2"],
                        "beta_Mkt": v["b_Mkt-RF"], "HML": v["b_HML"], "RMW": v["b_RMW"], "UMD": v["b_UMD"]} for b, v in h1["spanning_FF5_UMD"].items()])
    A("FF5 + UMD spanning regression, design period:")
    A("")
    A(md(sp, {"alpha_ann %": "{:.2f}"}))
    A("")
    A("### Style exposure and risk split of the books")
    A("")
    g = run.groupby("book")
    ex = pd.DataFrame({s: g[f"expo_{s}"].apply(lambda x: x.abs().mean()) for s in STYLES})
    ex.insert(0, "book", ex.index)
    A("Mean absolute book exposure to each style (std units per unit NAV), all months:")
    A("")
    A(md(ex.reset_index(drop=True), {s: "{:.3f}" for s in STYLES}))
    A("")
    tot = g[["var_industry", "var_style", "var_cross", "var_specific"]].mean()
    sp2 = (tot.div(tot.sum(axis=1), axis=0) * 100).reset_index()
    sp2.columns = ["book", "industry %", "style %", "industry-style cross %", "specific %"]
    A("Share of ex-ante monthly variance by the style model (mean over months with enough history):")
    A("")
    A(md(sp2, {c: "{:.1f}" for c in sp2.columns[1:]}))
    A("")
    A("## H2 detail: risk-model forecast quality")
    A("")
    rows = [{"period": k, "months": v["n_months"], "mean QLIKE PCA": v["mean_qlike_pca"], "mean QLIKE style": v["mean_qlike_style"],
             "gap": v["mean_qlike_diff_pca_minus_style"], "gap 95% CI": f"[{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}]",
             "bias std PCA": v["bias_std_pca"], "bias std style": v["bias_std_style"]} for k, v in h2["periods"].items()]
    A(md(pd.DataFrame(rows)))
    A("")
    A("Test portfolios are the 15 decile-spread characteristic portfolios, not optimised under either model. QLIKE = log(s2) + r2/s2 "
      "(lower is better); a bias std of 1 is a perfectly calibrated forecast. Per characteristic (design period):")
    A("")
    A(md(h2c.reset_index().rename(columns={"index": "char"})[["char", "q_pca", "q_style", "diff"]]))
    A("")
    A("## H3 detail: turnover cap")
    A("")
    rows = [{"period": k, "Sharpe T": v["sharpe_1"], "Sharpe V0": v["sharpe_2"], "diff": v["diff_ann"], "SE": v["se_ann"], "p (HAC)": v["p_two_sided"],
             "months": int(v["n"]), "turnover T": v["T_FF49_turnover"], "turnover V0": v["V0_FF49_turnover"]} for k, v in h3["periods"].items()]
    A(md(pd.DataFrame(rows)))
    A("")
    A("## H4 detail: overfitting audit of the 17 v1 books (2012-01..2019-12)")
    A("")
    A(f"- PBO (CSCV, 8 blocks, {h4['pbo_n_combinations']} combinations): **{h4['pbo']:.3f}**; median logit {h4['pbo_logit_median']:.2f}.")
    A(f"- v1 C_FF49: Sharpe {ci(h4['v1_C_FF49_sharpe'], *h4['v1_C_FF49_ci95'])}, PSR vs 0 {h4['v1_C_FF49_psr_vs_0']:.3f}, "
      f"expected best-of-17 noise Sharpe {h4['expected_max_sharpe_ann']:.2f}, DSR **{h4['v1_C_FF49_dsr']:.3f}**.")
    A(f"- DSR sensitivity by number of trials: {', '.join(f'{k}: {v:.3f}' for k, v in h4['dsr_sensitivity_by_n_trials'].items())} "
      "(22 = 17 + 5 new books; 68 = 17 books in each of 4 runs including 3 robustness runs).")
    A(f"- Best in-sample book: {h4['best_book_in_sample']} (Sharpe {h4['best_book_ann_sharpe']:.2f}); books with Sharpe > 0: {h4['n_books_sharpe_gt_0']} of 17.")
    A(f"- With the 5 new books ({h4['with_new_books']['n_columns']} columns): PBO {h4['with_new_books']['pbo']:.3f}.")
    A("")
    A("## D1 borrow assumptions (V0_FF49, fixed weights; assumptions, not data)")
    A("")
    b = bsw[bsw.book == "V0_FF49"].copy()
    b["Sharpe [95% CI]"] = [ci(a, c, d) for a, c, d in zip(b.sharpe, b.ci_lo, b.ci_hi)]
    A(md(b[["period", "borrow", "months", "mean_excess_ann_pct", "Sharpe [95% CI]"]], {"mean_excess_ann_pct": "{:.2f}"}))
    A("")
    be = pd.DataFrame([{"book": k, "period": p_, "breakeven flat fee (bp/yr)": v} for k, vv in bc["books"].items()
                       for p_, v in vv["breakeven_flat_fee_bp"].items()])
    A("Breakeven flat borrow fee (mean net excess return equals zero); negative means the book loses money before any borrow fee:")
    A("")
    A(md(be, {"breakeven flat fee (bp/yr)": "{:.0f}"}))
    A("")
    A("## D2 capacity (fixed $100M weights re-priced; an upper bound on net return at larger NAV)")
    A("")
    n = nav[nav.book == "V0_FF49"].copy()
    n["Sharpe [95% CI]"] = [ci(a, c, d) for a, c, d in zip(n.sharpe, n.ci_lo, n.ci_hi)]
    A(md(n[["period", "nav_musd", "mean_excess_ann_pct", "Sharpe [95% CI]", "cost_bps_yr", "gross_share_in_positions_over_5pct_adv"]],
         {"mean_excess_ann_pct": "{:.2f}", "cost_bps_yr": "{:.0f}", "nav_musd": "{:.0f}", "gross_share_in_positions_over_5pct_adv": "{:.2f}"}))
    A("")
    A("Per-trade participation (|trade| as a share of the name's 63-day median daily dollar volume, all trades done in one day):")
    A("")
    A(md(part[part.book == "V0_FF49"].drop(columns="book"), {"nav_musd": "{:.0f}", "median_pct_adv": "{:.2f}", "p95_pct_adv": "{:.1f}",
                                                           "share_over_5pct": "{:.3f}", "share_over_20pct": "{:.3f}"}))
    A("")
    cap = pd.DataFrame([{"book": k, "period": p_, "largest NAV with Sharpe within 0.10 of $100M ($M)": v}
                        for k, vv in bc["books"].items() for p_, v in vv["capacity_musd_sharpe_within_0.10_of_100M"].items()])
    A(md(cap, {"largest NAV with Sharpe within 0.10 of $100M ($M)": "{:.0f}"}))
    A("")
    v0n = nav[(nav.book == "V0_FF49") & (nav.period == SEENP)].sort_values("nav_musd")
    c_lo, c_hi = v0n.iloc[0], v0n.iloc[-1]
    first_big = v0n[v0n.gross_share_in_positions_over_5pct_adv > 0.05]
    A("Capacity is only meaningful where the book earns a positive net return. Where the design-period Sharpe is negative, the "
      "'capacity' rows describe noise, not a limit; use the seen-period rows and the cost curve instead. "
      f"V0_FF49 seen-period cost runs from {c_lo.cost_bps_yr:.0f} bp/yr at ${c_lo.nav_musd:.0f}M to {c_hi.cost_bps_yr:.0f} bp/yr at ${c_hi.nav_musd:.0f}M. "
      + (f"More than 5% of gross sits in positions above 5% of ADV from ${first_big.iloc[0].nav_musd:.0f}M, where the optimiser's "
         "5% ADV cap would bind and change the weights (not modelled here)." if len(first_big) else ""))
    A("")
    A("## D4 optimiser cross-check (skfolio MeanRisk vs cvxpy)")
    A("")
    rows = [{"month": k, "names": v["n"], "weight corr": v["weight_corr"], "objective gap (rel)": v["objective_gap_rel"],
             "max |w diff|": v["max_abs_weight_diff"]} for k, v in sk["months"].items()]
    A(md(pd.DataFrame(rows), {"weight corr": "{:.9f}", "objective gap (rel)": "{:.2e}", "max |w diff|": "{:.2e}"}))
    A("")
    A("Same problem in both (linear costs only, top-150 names, v1 PCA covariance). This checks the formulation and the production "
      "solver; skfolio cannot express the per-name |dw|^1.5 impact term, so it is not the production optimiser.")
    A("")
    A("## E1 exploratory: SHAP on the signal drivers (never headline)")
    A("")
    A(f"Boosted model on the 15 within-FF49 characteristics, train {shp['train_months']} months (to 2016-10), evaluate {shp['eval_months']} months "
      f"(2017-2019). Mean rank IC: boosted {shp['mean_ic_gbm']:.4f}, equal-weight composite {shp['mean_ic_composite']:.4f}; "
      f"difference {shp['ic_diff_gbm_minus_composite']:.4f}, 95% CI [{shp['ic_diff_ci95'][0]:.4f}, {shp['ic_diff_ci95'][1]:.4f}] "
      f"({'excludes' if shp['ic_diff_ci_excludes_zero'] else 'includes'} zero).")
    A("")
    A(md(pd.DataFrame({"theme": list(shp["shap_by_theme"]), "sum of mean |SHAP|": list(shp["shap_by_theme"].values())}), {"sum of mean |SHAP|": "{:.4f}"}))
    A("")
    A(md(shc.reset_index().rename(columns={"index": "characteristic"}).head(8), {"mean_abs_shap": "{:.4f}"}))
    A("")
    A("## Run integrity: solver failures (both numbers reported)")
    A("")
    f1 = run.groupby("book")["opt_failed"].sum()
    f0 = pre.groupby("book")["opt_failed"].sum()
    sh_pre = {b: sharpe_ci(slice_period(pre[pre.book == b].set_index("date")["excess_ret"], *CHOICE), 500)[0] for b in ["V0_FF49", "SIN_FF49"]}
    sh_post = {b: sharpe_ci(slice_period(run[run.book == b].set_index("date")["excess_ret"], *CHOICE), 500)[0] for b in ["V0_FF49", "SIN_FF49"]}
    A("The first full v2 run hit Clarabel numerical failures in some months (the solver raised; the month was traded flat). "
      "The optimiser now retries with a rescaled objective and looser tolerances. Solver-failure months per book, before and after:")
    A("")
    A(md(pd.DataFrame({"book": f0.index, "failed months before fix": f0.values, "failed months after fix": f1.reindex(f0.index).values})))
    A("")
    A(f"Design-period Sharpe before / after the fix: V0_FF49 {sh_pre['V0_FF49']:.2f} / {sh_post['V0_FF49']:.2f}; SIN_FF49 {sh_pre['SIN_FF49']:.2f} / {sh_post['SIN_FF49']:.2f}. "
      "(The pre-fix run is kept in `results/v2/runs/v2_prefix_solverfail`, git-ignored.)")
    A("")
    A("## F. Forward test (the only unseen data)")
    fp = ROOT / "results" / "v2" / "forward" / "forward.csv"
    if fp.exists():
        fwd = pd.read_csv(fp)
        A(f"Months with realised outcomes: {fwd['date'].nunique()}. Earliest meaningful read: 12 months.")
        A(md(fwd.groupby("book")["net_return"].agg(["count", "mean"]).reset_index()))
    else:
        A("No forward month has an outcome yet. The forward window starts with the 2026-11 signal month; `scripts/v2/forward.py` logs "
          "target weights and realised returns. Earliest read: 12 months of outcomes.")
    A("")
    out = ROOT / "research" / "results_v2.md"
    out.write_text("\n".join(o) + "\n", encoding="utf-8")
    print("wrote", out, len(o), "lines")


if __name__ == "__main__":
    main()
